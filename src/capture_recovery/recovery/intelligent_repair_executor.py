from __future__ import annotations

from dataclasses import dataclass

from capture_recovery.recovery.intelligent_repair_adapter import (
    AdaptedRepairPlan,
)

from capture_recovery.recovery.repair_action import (
    RepairResult,
)


@dataclass(slots=True, frozen=True)
class IntelligentExecutionResult:
    """
    Result of intelligent repair execution.
    """

    executed: tuple[RepairResult, ...]

    skipped: tuple[RepairResult, ...]



class IntelligentRepairExecutor:
    """
    Execute repair actions generated by the
    intelligent recovery pipeline.

    This class does not create repair actions.
    It only controls their execution.
    """

    def __init__(
        self,
        *,
        minimum_confidence: float = 0.80,
    ) -> None:

        self._minimum_confidence = (
            minimum_confidence
        )


    def execute(
        self,
        plan: AdaptedRepairPlan,
        project,
        report,
    ) -> IntelligentExecutionResult:
        """
        Execute an adapted repair plan.
        """

        executed = []

        skipped = []


        for action in plan.actions:

            confidence = getattr(
                action,
                "confidence",
                0.0,
            )


            if confidence < self._minimum_confidence:

                skipped.append(
                    self._skip_action(
                        action,
                        "Confidence too low",
                    )
                )

                continue


            result = action.execute(
                project,
                report,
            )

            executed.append(
                result,
            )


        return IntelligentExecutionResult(
            executed=tuple(executed),
            skipped=tuple(skipped),
        )


    def _skip_action(
        self,
        action,
        reason: str,
    ) -> RepairResult:
        """
        Create a skipped repair result.
        """

        return RepairResult.skipped_result(
            action=getattr(
                action,
                "action_type",
                "unknown",
            ),
            message=reason,
        )